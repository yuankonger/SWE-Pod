"""Exports a task of the payment-path company (tasks/<task>/task.json) as a Harbor task with several containers.

    python3 tools/export_harbor_payments.py <task> [--team] [--out harbor/<task>]

The company is the one company/payments builds (company/payments/build.sh makes its two images first): the API
(saleor/saleor), the payment app (saleor/apps, apps/stripe), the app's DynamoDB, and a stand-in for the payment
provider. Around it, as for every company here:

    main        the agent's seat: its repositories under /work, with their toolchains
    git         the company's git server; `main` there is what is deployed
    ci          deploy: when `main` of a repository moves it is deployed, and the systems are asked whether they answer
    core, payments   each system as last deployed from `main` (sidecars/service.py)
    provider, dynamodb   what the systems depend on and nobody here owns
    setup       once: installs the payment app in the API and configures it
    traffic     the shop's customers and staff: orders placed, paid, charged, refunded, all the while

A task of this company is an incident: something the running company does wrong. Nothing of the repositories is
judged. The verifier (tools/harbor_payments_score.py) waits for the deploy to catch up with `main`, places new
orders and compares what the provider's ledger says with what was asked.

Solo: one seat with both repositories and everything either owner can look at. --team: one seat per owner, each
with its own repository only (the other's is neither in the seat nor readable on the git server), its own
system's log, and what its NOTES.md names; a chat sidecar carries messages between them.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys


# How the payment app's deployed tree reaches the checkout that has its dependencies: files the last deployed tree
# had and this one has not are removed first (a deploy of a commit that deletes a file must not go on building it),
# then the tree is laid over. The first time, what the checkout itself tracks stands for the last deployed tree.
LAY_OVER = ("cd /work/payments && { [ -f .deployed-files ] || git ls-files | LC_ALL=C sort > .deployed-files; }"
            " && (cd /deployed/payments && find . -type f | sed 's#^\\./##' | LC_ALL=C sort) > .deployed-files.new"
            " && LC_ALL=C comm -23 .deployed-files .deployed-files.new | while IFS= read -r f; do rm -f -- \"$f\"; done"
            " && mv .deployed-files.new .deployed-files"
            " && tar -C /deployed/payments -cf - . | tar -C /work/payments -xf -")

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))
from export_harbor_company import CHAT_ADMIN, MCP_TEAM, MESSAGING, OWNER_TOKEN, SEAT_MEMORY, SEAT_NOTES, TOKENS, UNREACHABLE      # noqa: E402

OWNERS = ("core", "payments")
SECRETS = {"core_log": "core-log-83b1f0", "payments_log": "payments-log-c27d4a", "provider_viewer": "provider-view-19e6b5",
           "provider_admin": "provider-admin-6c1e0b93", "publishable": "pk_test_seedco51a7c0e2b9d4", "restricted": "rk_test_seedco8e03f6a1c7b2",
           "webhook": "whsec_seedco4d2a9f70c1e6", "traffic": "traffic-read-7d31c9", "app_key": "5b0c7e1f9a2d4c6e8f00112233445566778899aabbccddeeff0123456789abcd"}

