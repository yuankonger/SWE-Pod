"""Exports each task as a Harbor task directory (https://docs.harborframework.com/tasks/overview).

    python3 tools/export_harbor.py .          # writes harbor/<task>/ for every task under tasks/
    python3 tools/export_harbor.py . --check  # changes nothing; fails, naming the files, if harbor/ is not what
                                              # an export would write now

A Harbor task is one container and one agent, so the export is the task as one agent sees it with the whole
company: the `solo` brief as the instruction, the company with the task's starting state and history as the
environment, the task's rubric as the verifier, and the reference solution as the oracle. The layout is:

    harbor/<task>/instruction.md          the work, where the code is, and how it is judged: nothing the agent can find itself
    harbor/<task>/task.toml               name, timeouts, resources
    harbor/<task>/environment/Dockerfile  the toolchain image with the company copied to /work
    harbor/<task>/environment/work/       the company: services (with each owner's data/), platform, and the
                                          regression suite the agent can read and run (regression/)
    harbor/<task>/tests/test.sh           runs the rubric and writes /logs/verifier/reward.txt and rubric.json
    harbor/<task>/tests/rubric.toml       the task's whole rubric in one file, generated from the rubrics under tasks/
    harbor/<task>/tests/checks/           the check code: the hidden checks, and the verifier's own copy of the
                                          regression suite
    harbor/<task>/solution/solve.sh       copies the reference solution over the company

The exported directories are generated: change tasks/ and services/, then export again. Nothing under harbor/
is edited by hand; `--check` (also run by the kernel's tests) catches a copy that has fallen behind its source.
"""
import filecmp
import json
import os
import shutil
import sys
import tempfile

REPO = os.path.abspath(sys.argv[1])
sys.path.insert(0, REPO)

from kernel import rubric  # noqa: E402
from kernel.episode import check_dirs, prepare_workspace, seed_dir  # noqa: E402

# The instruction is the work and what cannot be found by looking: where the code is, and how the result is judged.
# How the company is laid out, how to run things and each system's rules are in the repository for the agent to find.
INSTRUCTION = """{brief}

The company's code is in `/work/services`. Its end-to-end regression tests are in `/work/regression`. A hidden
suite decides whether the work is right.
"""

TASK_TOML = """schema_version = "1.4"

[task]
name = "seedco/{task}"
description = "{title}"
keywords = ["swe-pod", "multi-service", "{structure}"]

[metadata]
category = "software-engineering"
change_type = "{change_type}"
owners_touched = {owners_touched}
criteria = {checks}
seed = "{seed}"

[verifier]
# The verifier starts nine services and Prometheus in the agent's container and drives them over HTTP.
timeout_sec = 1800.0
environment_mode = "shared"

[agent]
timeout_sec = 7200.0

[environment]
build_timeout_sec = 2400.0
cpus = 4
memory_mb = 8192
storage_mb = 20480
workdir = "/work"
"""

TEST_SH = """#!/bin/bash
# Runs the task's rubric against the company as the agent left it and writes the reward:
#   share of feature criteria passed x share of regression criteria passed   (see /tests/rubric.py)
# Nothing here trusts files the agent could have changed to grade itself: the stack runner, the checks, the
# regression suite, the production history, the released mobile build and the driver that replays it all come
# from /tests. Before the company is started, whatever the agent left listening on its ports is killed.
mkdir -p /logs/verifier
python3 /tests/rubric.py --workspace /work --checks /tests /tests/checks/* --seed /tests/seed --platform /tests/platform \\
    --out /logs/verifier > /logs/verifier/output.txt 2>&1
[ -f /logs/verifier/reward.txt ] || echo 0 > /logs/verifier/reward.txt
cat /logs/verifier/reward.txt
"""

SOLVE_SH = """#!/bin/bash
# The reference solution: every file it changes or adds, copied over the company.
set -euo pipefail
cp -r /solution/services/. /work/services/
"""


RUBRIC_HEADER = """# GENERATED by tools/export_harbor.py. Do not edit: change the source and export again.
# The whole rubric of {task}, put together from:
{sources}
# kernel/rubric.py (here: /tests/rubric.py) runs it. Format and reward: see that file's header.
"""


def merged_rubric(task: str, task_dir: str) -> str:
    """The task's rubric files as one: each holds only `[[criterion]]` tables, so one after the other is the whole list."""
    sources = [os.path.join(d, "rubric.toml") for d in check_dirs(task_dir) if os.path.isfile(os.path.join(d, "rubric.toml"))]
    parts = [RUBRIC_HEADER.format(task=task, sources="\n".join("#   " + os.path.relpath(s, REPO) for s in sources))]
    for source in sources:
        parts.append("# " + "=" * 100 + "\n# from " + os.path.relpath(source, REPO) + "\n# " + "=" * 100 + "\n\n" + open(source).read().strip() + "\n")
    return "\n".join(parts)


def export(task: str, root: str):
    task_dir = os.path.join(REPO, "tasks", task)
    info = json.load(open(os.path.join(task_dir, "task.json")))
    out = os.path.join(root, task)
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)

    # environment: the toolchain image plus the company with the task's starting state and each owner's data
    env = os.path.join(out, "environment")
    work = prepare_workspace(REPO, task_dir, os.path.join(env, "work"))
    dockerfile = open(os.path.join(REPO, "docker", "Dockerfile")).read().rstrip("\n")
    open(os.path.join(env, "Dockerfile"), "w").write(
        "# The SWE-Pod toolchain (docker/Dockerfile in the SWE-Pod repository), then the company in /work.\n"
        + dockerfile.split("\n", 2)[2] + "\n\nCOPY work /work\n")

    brief = info["solo_brief"].replace("\n\nYou own the whole company.", "\n\nThe whole company is yours to change.")
    open(os.path.join(out, "instruction.md"), "w").write(INSTRUCTION.format(
        brief=brief.replace("`core/docs/", "`/work/services/core/docs/").replace("`payments/docs/", "`/work/services/payments/docs/")))

    # tests: the rubric runner, the checks, and everything they must not take from the agent's side
    tests = os.path.join(out, "tests")
    for i, source in enumerate(check_dirs(task_dir)):     # in order: a later directory's rubric adds to an earlier one's
        name = "{}_{}_{}".format(i, os.path.basename(os.path.dirname(source)), os.path.basename(source))
        shutil.copytree(source, os.path.join(tests, "checks", name), ignore=shutil.ignore_patterns("__pycache__", "rubric.toml"))
    open(os.path.join(tests, "rubric.toml"), "w").write(merged_rubric(task, task_dir))
    shutil.copy(os.path.join(REPO, "kernel", "rubric.py"), os.path.join(tests, "rubric.py"))
    shutil.copytree(os.path.join(REPO, "platform"), os.path.join(tests, "platform"), ignore=shutil.ignore_patterns("__pycache__"))
    seed = seed_dir(task_dir)
    if seed:
        shutil.copytree(seed, os.path.join(tests, "seed"))
    open(os.path.join(tests, "test.sh"), "w").write(TEST_SH)
    os.chmod(os.path.join(tests, "test.sh"), 0o755)
    checks = len(rubric.load([tests]))
    assert [c["id"] for c in rubric.load([tests])] == [c["id"] for c in rubric.load(check_dirs(task_dir))], "the merged rubric lost a criterion"

    # solution: the oracle
    shutil.copytree(os.path.join(task_dir, "solution"), os.path.join(out, "solution"))
    open(os.path.join(out, "solution", "solve.sh"), "w").write(SOLVE_SH)
    os.chmod(os.path.join(out, "solution", "solve.sh"), 0o755)

    quote = lambda text: text.replace("\\", "\\\\").replace('"', '\\"')  # noqa: E731
    open(os.path.join(out, "task.toml"), "w").write(TASK_TOML.format(
        task=task.replace("_", "-"), title=quote(info["title"]), structure=quote(info["structure"].split(";")[0]),
        change_type=quote(info["change_type"]), seed=quote(info["seed"]), checks=checks,
        owners_touched=len(os.listdir(os.path.join(task_dir, "solution", "services")))))
    return out, checks


def differences(ours: str, theirs: str, rel: str = "") -> list:
    """Files that differ between two directory trees, or are in only one of them."""
    cmp = filecmp.dircmp(ours, theirs, ignore=["__pycache__", ".DS_Store"])
    found = [os.path.join(rel, f) + " (only in the fresh export)" for f in cmp.left_only]
    found += [os.path.join(rel, f) + " (only in harbor/)" for f in cmp.right_only]
    _, differ, errors = filecmp.cmpfiles(ours, theirs, cmp.common_files, shallow=False)
    found += [os.path.join(rel, f) + " (differs)" for f in differ + errors]
    for d in cmp.common_dirs:
        found += differences(os.path.join(ours, d), os.path.join(theirs, d), os.path.join(rel, d))
    return found


TASKS = sorted(n for n in os.listdir(os.path.join(REPO, "tasks")) if os.path.isfile(os.path.join(REPO, "tasks", n, "task.json")))
if "--check" in sys.argv[2:]:
    fresh = tempfile.mkdtemp(prefix="seedco-harbor-")
    stale = []
    for name in TASKS:
        export(name, fresh)
        there = os.path.join(REPO, "harbor", name)
        stale += [os.path.join("harbor", name, f) for f in (differences(os.path.join(fresh, name), there) if os.path.isdir(there) else ["(not exported)"])]
    shutil.rmtree(fresh, ignore_errors=True)
    print("\n".join(["harbor/ is behind its sources. Run: python3 tools/export_harbor.py ."] + stale[:40]) if stale else "harbor/ is up to date")
    sys.exit(1 if stale else 0)
for name in TASKS:
    out, checks = export(name, os.path.join(REPO, "harbor"))
    print("{}: {} criteria, {} files".format(os.path.relpath(out, REPO), checks, sum(len(f) for _, _, f in os.walk(out))))
